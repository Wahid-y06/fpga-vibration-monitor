"""Design tools.

    python -m vibmodel generate   # write rtl/vib_params.vh and board/vib_demo.hex
    python -m vibmodel report     # print the scenario/alarm table and save plots to docs/
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from .config import (BANDS, BLOCK, CHANNELS, COEF_FRAC, COEF_W, CRIT, DC_K, DW, FS,
                     INPUT_SHIFT, N_CH, PERSIST_BLOCKS, ROM_LEN, WARN)
from .design import band_coefficients, frequency_response, pole_radius
from .reference import Monitor
from .signals import SCENARIOS, generate, looped

ROOT = Path(__file__).resolve().parent.parent
LEVEL_NAMES = ("normal", "WARNING", "CRITICAL")


def _vec(values, width):
    """Verilog concatenation with element 0 in the least significant bits."""
    mask = (1 << width) - 1
    parts = [f"{width}'h{v & mask:0{(width + 3) // 4}X}" for v in reversed(values)]
    return "{" + ", ".join(parts) + "}"


def write_params(path: Path) -> None:
    coefs = [c for band in band_coefficients() for c in band]
    lines = [
        "// Generated by `python -m vibmodel generate` - do not edit by hand.",
        f"// fs = {FS} Hz; bands: " + ", ".join(f"{n} {f:.1f} Hz Q{q}" for n, f, q in BANDS),
        f"localparam integer VIB_DW          = {DW};",
        f"localparam integer VIB_INPUT_SHIFT = {INPUT_SHIFT};",
        f"localparam integer VIB_DC_K        = {DC_K};",
        f"localparam integer VIB_COEF_W      = {COEF_W};",
        f"localparam integer VIB_COEF_FRAC   = {COEF_FRAC};",
        f"localparam integer VIB_N_BANDS     = {len(BANDS)};",
        f"localparam integer VIB_N_CH        = {N_CH};",
        f"localparam integer VIB_PERSIST     = {PERSIST_BLOCKS};",
        "// per band: b0, b1, b2, -a1, -a2 (Q2.16); element 0 = band 0 b0",
        f"localparam [{len(coefs) * COEF_W - 1}:0] VIB_COEFS = {_vec(coefs, COEF_W)};",
        "// alarm thresholds per channel (overall, " + ", ".join(b[0] for b in BANDS) + ")",
        f"localparam [{N_CH * 32 - 1}:0] VIB_WARN = {_vec(WARN, 32)};",
        f"localparam [{N_CH * 32 - 1}:0] VIB_CRIT = {_vec(CRIT, 32)};",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_demo_rom(path: Path) -> None:
    """All scenarios back to back, ROM_LEN samples each, one hex word per line."""
    words = []
    for name in SCENARIOS:
        words += [f"{int(s) & 0xFFFF:04X}" for s in generate(name, ROM_LEN)]
    path.write_text("\n".join(words) + "\n", encoding="utf-8")


def report(out_dir: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    for (name, f0, q), c in zip(BANDS, band_coefficients()):
        print(f"band {name:<10} f0 {f0:7.1f} Hz  Q {q:<4} pole radius {pole_radius(c):.5f}")
    print()
    print(f"{'scenario':<14}" + "".join(f"{c:>12}" for c in CHANNELS))
    results = {}
    for name in SCENARIOS:
        res = Monitor(list(WARN), list(CRIT)).run(looped(name, 16 * BLOCK))
        results[name] = res
        last = res[-1]
        print(f"{name:<14}" + "".join(f"{LEVEL_NAMES[lv]:>12}" for lv in last.levels))

    out_dir.mkdir(exist_ok=True)
    freqs = np.logspace(0.5, np.log10(FS / 2), 800)
    fig, ax = plt.subplots(figsize=(9, 4.5))
    for (name, f0, q), c in zip(BANDS, band_coefficients()):
        ax.semilogx(freqs, 20 * np.log10(frequency_response(c, freqs) + 1e-12),
                    label=f"{name} ({f0:.0f} Hz, Q {q})")
    ax.set_ylim(-40, 3)
    ax.set_xlabel("Frequency (Hz)")
    ax.set_ylabel("Gain (dB)")
    ax.set_title("Filter bank response (quantized Q2.16 coefficients)")
    ax.grid(which="both", alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(out_dir / "filter_response.png", dpi=120)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 4.5))
    width = 0.15
    x = np.arange(N_CH)
    for i, (name, res) in enumerate(results.items()):
        energies = np.median(np.array([r.energies for r in res[4:]]), axis=0)
        ax.bar(x + (i - 2) * width, energies, width, label=name)
    for ch in range(N_CH):
        ax.hlines([WARN[ch], CRIT[ch]], ch - 0.42, ch + 0.42,
                  colors=["#e69500", "#d62728"], linestyles="--", lw=1)
    ax.set_yscale("log")
    ax.set_xticks(x, CHANNELS)
    ax.set_ylabel("Block energy (LSB²)")
    ax.set_title("Band energy per fault scenario (dashed: warning / critical limits)")
    ax.legend(fontsize=8)
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(out_dir / "band_energy.png", dpi=120)
    plt.close(fig)
    print(f"\nplots written to {out_dir}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="vibmodel")
    ap.add_argument("command", choices=("generate", "report"))
    args = ap.parse_args(argv)
    if args.command == "generate":
        write_params(ROOT / "rtl" / "vib_params.vh")
        write_demo_rom(ROOT / "board" / "vib_demo.hex")
        print("wrote rtl/vib_params.vh and board/vib_demo.hex")
    else:
        report(ROOT / "docs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
